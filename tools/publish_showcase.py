#!/usr/bin/env python3
"""Upload a showcase attachment and replace only its marked README section."""
import argparse
import json
from pathlib import Path
import re
import subprocess
import tempfile

START = "<!-- showcase-video:start -->"
END = "<!-- showcase-video:end -->"
ATTACHMENT = re.compile(r"https://github\.com/user-attachments/assets/[A-Za-z0-9-]+(?:\.mp4)?")
TITLE = "Showcase video (CI media)"


def updated_readme(text, url, revision):
    if not ATTACHMENT.fullmatch(url):
        raise ValueError("expected a GitHub user-attachment URL")
    if not re.fullmatch(r"[0-9a-f]{40}", revision):
        raise ValueError("expected a full source commit SHA")
    if text.count(START) != 1 or text.count(END) != 1:
        raise ValueError("README must contain exactly one showcase marker pair")
    before, rest = text.split(START)
    _, after = rest.split(END)
    if END in before:
        raise ValueError("showcase markers are reversed")
    return (before + START + "\n\n" + url + "\n\n"
            + f"*Autogenerated showcase · 30 fps · source `{revision}`.*\n\n" + END + after)


def gh(*args):
    return subprocess.check_output(["gh", *args], text=True).strip()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("video", type=Path)
    parser.add_argument("--repo", required=True)
    parser.add_argument("--revision", required=True)
    parser.add_argument("--readme", type=Path, default=Path("README.md"))
    args = parser.parse_args()
    text = args.readme.read_text()
    # Validate the local document before creating any remote content.
    updated_readme(text, "https://github.com/user-attachments/assets/validation", args.revision)
    if not args.video.is_file() or not 0 < args.video.stat().st_size < 10_000_000:
        parser.error("video must exist and be below GitHub's 10 MB attachment limit")
    issues = json.loads(gh("issue", "list", "--repo", args.repo, "--state", "all",
                           "--search", f'"{TITLE}" in:title', "--json", "number,title"))
    matches = [issue for issue in issues if issue["title"] == TITLE]
    if len(matches) > 1:
        raise RuntimeError("multiple CI media issues found; keep one canonical issue")
    # GitHub CLI rewrites this standalone image reference into an inline video URL.
    with tempfile.TemporaryDirectory() as directory:
        body = Path(directory) / "body.md"
        body.write_text(f"Generated from `{args.revision}`. Updated automatically by CI.\n\n"
                        f"![]({args.video.resolve()})\n")
        if matches:
            issue = str(matches[0]["number"])
            gh("issue", "edit", issue, "--repo", args.repo, "--body-file", str(body),
               "--attach", str(args.video.resolve()))
        else:
            issue = gh("issue", "create", "--repo", args.repo, "--title", TITLE,
                       "--body-file", str(body), "--attach", str(args.video.resolve()))
    posted = json.loads(gh("issue", "view", issue, "--repo", args.repo, "--json", "body"))
    urls = ATTACHMENT.findall(posted["body"])
    if len(urls) != 1:
        raise RuntimeError("upload did not produce exactly one video attachment URL")
    args.readme.write_text(updated_readme(text, urls[0], args.revision))
    print(urls[0])


if __name__ == "__main__":
    main()
